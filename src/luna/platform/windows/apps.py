"""Windows app catalog (``Get-StartApps``) and launcher (``shell:AppsFolder``).

Design notes (ADR 0008):

* Discovery runs PowerShell with a **fixed argument list** (no ``shell=True``, no text from
  the user or the LLM is ever interpolated into it), a timeout, and forces UTF-8 output so
  Cyrillic names survive. The JSON is parsed defensively; entries with a malformed name or
  an AppID that matches no allowed form (``classify_app_id``) are dropped.
* Failure policy: ``refresh()`` keeps the previous snapshot (memory or on-disk cache) and
  logs a warning when PowerShell fails, times out, prints garbage or returns **no apps**
  (an empty result is never accepted as success and never overwrites the cache); it raises
  ``ProviderUnavailable`` only when there is nothing cached to fall back on. ``list_apps()``
  is served from the in-memory snapshot, then from the cache file, and scans only if both are
  empty. After a failed scan with nothing cached, further calls raise ``ProviderUnavailable``
  for ``BACKOFF_S`` seconds instead of re-running PowerShell. A scan can block for up to
  ``timeout_s``: do not call ``list_apps()`` / ``launch()`` for the first time from the audio
  or UI thread (the background refresh is wired in #21).
* Launching uses ``os.startfile("shell:AppsFolder\\<AppID>")`` (ShellExecute "open" verb with
  one argument; no command line is built, no arguments are passed). It is chosen over
  spawning ``explorer.exe`` because it needs no subprocess and no quoting. The AppID must come
  from an ``AppEntry`` that is currently in the catalog and must match an allowed form.
"""

from __future__ import annotations

import contextlib
import json
import logging
import os
import re
import subprocess
import tempfile
import threading
import time
import unicodedata
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path, PureWindowsPath
from typing import Any

from luna.core.errors import ProviderUnavailable, ToolError
from luna.platform.base import AppCatalog, AppEntry
from luna.platform.browser import validate_web_url

log = logging.getLogger(__name__)

DEFAULT_TIMEOUT_S = 20.0
BACKOFF_S = 60.0
CACHE_FILENAME = "apps.json"
MAX_CACHE_BYTES = 2 * 1024 * 1024
MAX_CACHE_APPS = 5000
_CACHE_VERSION = 1
_MAX_ID_CHARS = 2048
_MAX_NAME_CHARS = 256

# Output is forced to UTF-8 so non-ASCII names do not depend on the console code page.
_POWERSHELL_SCRIPT = (
    "[Console]::OutputEncoding = [System.Text.Encoding]::UTF8; "
    "Get-StartApps | ConvertTo-Json -Compress"
)

# (argv, timeout_s) -> completed process with bytes stdout/stderr. Injectable for tests.
Runner = Callable[[Sequence[str], float], "subprocess.CompletedProcess[bytes]"]
StartFile = Callable[[str], object]
Clock = Callable[[], float]

_AUMID_RE = re.compile(r"[A-Za-z0-9._-]+![A-Za-z0-9._-]+", re.ASCII)
# Also seen on real machines: ``Microsoft.AutoGenerated.{GUID}`` and ``zoom.us.Zoom Video Meetings``
# (braces and single inner spaces; still no separators, colons or other punctuation).
_SIMPLE_RE = re.compile(r"[A-Za-z0-9._{}-]+(?: [A-Za-z0-9._{}-]+)*", re.ASCII)
_GUID_PREFIX_RE = re.compile(r"\{[0-9A-Fa-f-]{36}\}", re.ASCII)
_CLSID_RE = re.compile(r"::\{[0-9A-Fa-f-]{36}\}", re.ASCII)
_DRIVE_RE = re.compile(r"[A-Za-z]:\\", re.ASCII)
_SEGMENT_FORBIDDEN = frozenset('\\/:*?"<>|')
# Only document/program types a user would "open"; scripts, installers and shortcuts
# (.bat .cmd .ps1 .vbs .js .msi .com .scr .lnk ...) never enter the catalog.
_PATH_EXTENSIONS = frozenset({".exe", ".html", ".htm", ".chm", ".pdf", ".txt", ".rtf"})


def _segments_ok(segments: Sequence[str]) -> bool:
    if not segments:
        return False
    for seg in segments:
        if not seg or seg in (".", "..") or seg != seg.strip() or seg.endswith("."):
            return False
        if not seg.isprintable() or any(ch in _SEGMENT_FORBIDDEN for ch in seg):
            return False
        if unicodedata.normalize("NFKC", seg) != seg:  # fullwidth / compatibility lookalikes
            return False
    return True


def classify_app_id(app_id: object) -> str | None:
    """Return the form of an allowed AppID, or ``None`` if it matches no allowed form.

    Forms (all seen in real ``Get-StartApps`` output): ``aumid`` (``Pkg_pub!App``),
    ``simple`` (``Chrome``), ``guid_path`` (``{GUID}\\relative\\path``), ``clsid``
    (``::{GUID}``), ``abs_path`` (``D:\\dir\\app.exe`` with a document/program extension) and
    ``url`` (http/https accepted by ``validate_web_url``). Everything else (UNC paths,
    ``..``, ``file://``, other schemes such as ``mailto:``/``ms-settings:``, scripts) is rejected.
    """
    if not isinstance(app_id, str) or not app_id or len(app_id) > _MAX_ID_CHARS:
        return None
    if app_id.lower().startswith(("http://", "https://")):
        try:
            validate_web_url(app_id)
        except ValueError:
            return None
        return "url"
    if _AUMID_RE.fullmatch(app_id):
        return "aumid"
    if _SIMPLE_RE.fullmatch(app_id):
        return "simple" if set(app_id) != {"."} else None
    if _CLSID_RE.fullmatch(app_id):
        return "clsid"
    if _GUID_PREFIX_RE.match(app_id) and app_id[38:39] == "\\":
        return "guid_path" if _segments_ok(app_id[39:].split("\\")) else None
    if _DRIVE_RE.match(app_id):
        parts = app_id[3:].split("\\")
        if _segments_ok(parts) and PureWindowsPath(parts[-1]).suffix.lower() in _PATH_EXTENSIONS:
            return "abs_path"
    return None


def is_safe_app_id(app_id: object) -> bool:
    """True if ``app_id`` matches one of the allowed forms (see ``classify_app_id``)."""
    return classify_app_id(app_id) is not None


def _powershell_path() -> str:
    # Never a bare name: CreateProcess would search the current directory first.
    root = os.environ.get("SYSTEMROOT") or r"C:\Windows"
    return str(Path(root) / "System32" / "WindowsPowerShell" / "v1.0" / "powershell.exe")


def powershell_argv() -> list[str]:
    return [
        _powershell_path(),
        "-NoProfile",
        "-NonInteractive",
        "-Command",
        _POWERSHELL_SCRIPT,
    ]


def _default_runner(argv: Sequence[str], timeout_s: float) -> subprocess.CompletedProcess[bytes]:
    flags = getattr(subprocess, "CREATE_NO_WINDOW", 0)
    return subprocess.run(
        list(argv),  # fixed argv, no shell, no untrusted input
        capture_output=True,
        timeout=timeout_s,
        check=False,
        stdin=subprocess.DEVNULL,
        creationflags=flags,
    )


def default_cache_dir(env: Mapping[str, str] | None = None) -> Path:
    """``%LOCALAPPDATA%\\LUNA`` (falls back to ``~/AppData/Local/LUNA`` if unset)."""
    base = (env if env is not None else os.environ).get("LOCALAPPDATA")
    root = Path(base) if base else Path.home() / "AppData" / "Local"
    return root / "LUNA"


def _to_entry(item: object) -> AppEntry | None:
    if not isinstance(item, dict):
        return None
    name, app_id = item.get("Name"), item.get("AppID")
    if not isinstance(name, str) or not name.strip() or len(name) > _MAX_NAME_CHARS:
        return None
    if not name.isprintable() or not isinstance(app_id, str):
        return None
    if classify_app_id(app_id) is None:
        log.debug("excluding app %r: id %r matches no allowed form", name, app_id)
        return None
    return AppEntry(name=name.strip(), app_id=app_id)


def parse_start_apps(raw: bytes | str) -> tuple[AppEntry, ...]:
    """Parse ``Get-StartApps | ConvertTo-Json`` output.

    Handles empty output, a single object instead of an array, a UTF-8 BOM, and drops
    malformed entries and ids of a disallowed form. Raises ``ValueError`` if the text is not
    valid JSON of the expected shape.
    """
    text = raw.decode("utf-8-sig") if isinstance(raw, bytes) else raw.lstrip("\ufeff")
    if not text.strip():
        return ()
    data: Any = json.loads(text)
    if data is None:
        return ()
    if isinstance(data, dict):
        data = [data]
    if not isinstance(data, list):
        raise ValueError("unexpected JSON shape from Get-StartApps")
    seen: set[str] = set()
    entries: list[AppEntry] = []
    for item in data:
        entry = _to_entry(item)
        if entry is None:
            continue
        if entry.app_id in seen:
            continue
        seen.add(entry.app_id)
        entries.append(entry)
    return tuple(entries)


class WindowsAppCatalog:
    """``AppCatalog`` backed by ``Get-StartApps`` with an on-disk JSON cache."""

    def __init__(
        self,
        cache_dir: Path | None = None,
        runner: Runner | None = None,
        timeout_s: float = DEFAULT_TIMEOUT_S,
        clock: Clock = time.monotonic,
        backoff_s: float = BACKOFF_S,
    ) -> None:
        self._cache_file = (cache_dir or default_cache_dir()) / CACHE_FILENAME
        self._runner = runner or _default_runner
        self._timeout_s = timeout_s
        self._clock = clock
        self._backoff_s = backoff_s
        self._lock = threading.Lock()
        self._snapshot: tuple[AppEntry, ...] | None = None
        self._failed_at: float | None = None
        self._failure: ProviderUnavailable | None = None

    def list_apps(self) -> tuple[AppEntry, ...]:
        snap = self._snapshot
        if snap is not None:
            return snap
        with self._lock:
            if self._snapshot is None:
                cached = self._read_cache()
                if cached is not None:
                    self._snapshot = cached
                else:
                    self._scan_locked()
            snap = self._snapshot
            assert snap is not None
            return snap

    def refresh(self) -> None:
        with self._lock:
            self._scan_locked()

    # -- internals -----------------------------------------------------------------------

    def _scan_locked(self) -> None:
        if (
            self._snapshot is None
            and self._failed_at is not None
            and self._failure is not None
            and self._clock() - self._failed_at < self._backoff_s
        ):
            raise ProviderUnavailable(f"app scan is backing off: {self._failure}")
        try:
            entries = self._scan()
        except ProviderUnavailable as exc:
            fallback = self._snapshot if self._snapshot is not None else self._read_cache()
            if fallback is None:
                self._failed_at, self._failure = self._clock(), exc
                raise
            log.warning("app scan failed, keeping cached catalog: %s", exc)
            self._snapshot = fallback
            return
        self._failed_at = self._failure = None
        self._write_cache(entries)
        self._snapshot = entries  # single assignment: readers see the old or the new tuple

    def _scan(self) -> tuple[AppEntry, ...]:
        try:
            proc = self._runner(powershell_argv(), self._timeout_s)
        except subprocess.TimeoutExpired as exc:
            raise ProviderUnavailable(f"Get-StartApps timed out after {self._timeout_s}s") from exc
        except OSError as exc:
            raise ProviderUnavailable(f"cannot run PowerShell: {exc}") from exc
        if proc.returncode != 0:
            raise ProviderUnavailable(f"Get-StartApps failed with exit code {proc.returncode}")
        try:
            entries = parse_start_apps(proc.stdout)
        except (ValueError, RecursionError) as exc:  # JSON / UTF-8 decoding errors
            raise ProviderUnavailable(f"cannot parse Get-StartApps output: {exc}") from exc
        if not entries:
            raise ProviderUnavailable("Get-StartApps returned no apps")
        return entries

    def _read_cache(self) -> tuple[AppEntry, ...] | None:
        try:
            if self._cache_file.stat().st_size > MAX_CACHE_BYTES:
                return None
            data = json.loads(self._cache_file.read_text(encoding="utf-8"))
            if data.get("version") != _CACHE_VERSION or len(data["apps"]) > MAX_CACHE_APPS:
                return None
            raw = ({"Name": a["name"], "AppID": a["app_id"]} for a in data["apps"])
            entries = tuple(e for e in map(_to_entry, raw) if e is not None)
        except (OSError, ValueError, RecursionError, KeyError, TypeError, AttributeError):
            return None
        return entries or None

    def _write_cache(self, entries: Sequence[AppEntry]) -> None:
        payload = {
            "version": _CACHE_VERSION,
            "apps": [{"name": e.name, "app_id": e.app_id} for e in entries],
        }
        tmp_name: str | None = None
        try:
            self._cache_file.parent.mkdir(parents=True, exist_ok=True)
            fd, tmp_name = tempfile.mkstemp(
                dir=self._cache_file.parent, prefix="apps-", suffix=".tmp"
            )
            with os.fdopen(fd, "w", encoding="utf-8") as fh:
                json.dump(payload, fh, ensure_ascii=False)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp_name, self._cache_file)
        except OSError as exc:  # the cache is an optimization, never fatal
            log.warning("cannot write app cache %s: %s", self._cache_file, exc)
            if tmp_name is not None:
                with contextlib.suppress(OSError):
                    os.unlink(tmp_name)


class WindowsAppLauncher:
    """``AppLauncher`` that starts catalog entries via ``shell:AppsFolder\\<AppID>``."""

    def __init__(self, catalog: AppCatalog, startfile: StartFile | None = None) -> None:
        self._catalog = catalog
        self._startfile = startfile or getattr(os, "startfile", None)

    def launch(self, app: AppEntry) -> None:
        if not isinstance(app, AppEntry):
            raise ToolError("app is not in the catalog")
        try:
            known = app in self._catalog.list_apps()
        except ProviderUnavailable as exc:
            raise ToolError(f"app catalog unavailable: {exc}") from exc
        if not known:
            raise ToolError("app is not in the catalog")
        if not is_safe_app_id(app.app_id):
            raise ToolError(f"unsafe app id for {app.name!r}")
        if self._startfile is None:
            raise ToolError("launching apps is only supported on Windows")
        try:
            self._startfile("shell:AppsFolder\\" + app.app_id)
        except OSError as exc:
            raise ToolError(f"cannot launch {app.name!r}: {exc}") from exc
