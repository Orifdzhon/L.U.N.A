"""View protocols implemented by ``luna.ui.qt`` and faked in tests (no Qt import)."""

from __future__ import annotations

from collections.abc import Callable
from typing import Protocol

from luna.ui.shell.state import ConversationLine, IconState, TrayMenuState


class UiThread(Protocol):
    def post(self, fn: Callable[[], None]) -> None:
        """Any thread; ``fn`` runs on the UI thread."""
        ...


class TrayView(Protocol):
    """All methods: UI thread only."""

    def set_state(self, state: IconState, tooltip: str) -> None: ...
    def set_menu(self, menu: TrayMenuState) -> None: ...
    def notify(self, title: str, text: str) -> None: ...
    def show(self) -> None: ...
    def hide(self) -> None: ...


class WindowView(Protocol):
    """All methods: UI thread only."""

    def append(self, line: ConversationLine) -> None: ...
    def set_status(self, text: str) -> None: ...
    def set_input_busy(self, busy: bool) -> None: ...
    def set_state(self, state: IconState, caption: str) -> None: ...
    def set_voice_available(self, available: bool, reason: str) -> None: ...
    def show(self) -> None: ...
    def hide(self) -> None: ...
    @property
    def visible(self) -> bool: ...
